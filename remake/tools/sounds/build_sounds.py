#!/usr/bin/env python3
"""Renders the new CC0 sound set into remake/Content/sounds from tools/sounds/sources.json.

Usage:  python3 tools/sounds/build_sounds.py [--cache DIR]
Needs:  ffmpeg (with libvorbis) on PATH, Python packages numpy and py7zr.

Steps per sound: download + unpack the source pack (cached), decode to mono 44.1 kHz,
optional ffmpeg filter, cut [start, start+length], fade out, optional seamless loop
(crossfade), peak-normalise, encode (Ogg Vorbis; loops as 16-bit WAV). Also rewrites the generated sound table
in remake/ASSETS-LICENSES.md. Output is deterministic for the same inputs.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import urllib.parse
import urllib.request
import zipfile

import numpy as np

SR = 44100
HERE = os.path.dirname(os.path.abspath(__file__))
REMAKE = os.path.dirname(os.path.dirname(HERE))
OUT_DIR = os.path.join(REMAKE, "Content", "sounds")
LICENSES = os.path.join(REMAKE, "ASSETS-LICENSES.md")
BEGIN, END = "<!-- sounds:begin (generated by tools/sounds/build_sounds.py) -->", "<!-- sounds:end -->"


def fetch_pack(key, pack, cache):
    dest = os.path.join(cache, key)
    if os.path.isdir(dest) and os.listdir(dest):
        return dest
    os.makedirs(dest, exist_ok=True)
    url = pack["download"]
    name = urllib.parse.unquote(url.rsplit("/", 1)[1])
    archive = os.path.join(cache, "_dl_" + name)
    if not os.path.exists(archive):
        print("download", url)
        with urllib.request.urlopen(url) as r, open(archive + ".part", "wb") as f:
            shutil.copyfileobj(r, f)
        os.replace(archive + ".part", archive)
    if name.endswith(".zip"):
        zipfile.ZipFile(archive).extractall(dest)
    elif name.endswith(".7z"):
        import py7zr
        with py7zr.SevenZipFile(archive) as z:
            z.extractall(dest)
    else:
        shutil.copy(archive, os.path.join(dest, name))
    return dest


def decode(path, af=None):
    cmd = ["ffmpeg", "-v", "error", "-i", path]
    if af:
        cmd += ["-af", af]
    cmd += ["-ac", "1", "-ar", str(SR), "-f", "f32le", "-"]
    raw = subprocess.run(cmd, check=True, capture_output=True).stdout
    return np.frombuffer(raw, dtype=np.float32).astype(np.float64)


def synth(kind, length):
    """Original procedural sounds (dedicated CC0 by this project)."""
    if kind != "ricochet":
        raise ValueError(kind)
    rng = np.random.default_rng(1234)
    t = np.arange(int(length * SR)) / SR
    freq = 3400.0 * (1.0 - 0.55 * t / length) * (1.0 + 0.012 * np.sin(2 * np.pi * 38 * t))
    whine = np.sin(2 * np.pi * np.cumsum(freq) / SR) * np.exp(-t / (length * 0.38))
    whine *= np.minimum(1.0, t / 0.004)
    noise = rng.standard_normal(len(t)) * np.exp(-t / 0.012)
    hit = np.convolve(noise, np.ones(4) / 4, "same")  # soft high-cut on the impact click
    return 0.8 * whine + 0.6 * hit


def render(spec, cache, packs):
    if spec["pack"] == "synth":
        x = synth(spec["synth"], spec["length"])
    else:
        root = fetch_pack(spec["pack"], packs[spec["pack"]], cache)
        x = decode(os.path.join(root, spec["file"]), spec.get("af"))
    start = int(spec.get("start", 0.0) * SR)
    length = spec.get("length")
    loop = spec.get("loop", False)
    xfade = int(0.12 * SR) if loop else 0
    end = len(x) if length is None else min(len(x), start + int(length * SR) + xfade)
    x = x[start:end].copy()
    if loop:
        # seamless loop: blend the tail into the head with an equal-power crossfade
        body, tail = x[:-xfade].copy(), x[-xfade:]
        ramp = np.linspace(0.0, np.pi / 2, xfade)
        body[:xfade] = body[:xfade] * np.sin(ramp) + tail * np.cos(ramp)
        x = body
    else:
        fade = int(spec.get("fade", min(0.03, len(x) / SR / 4)) * SR)
        if fade > 0:
            x[-fade:] *= np.linspace(1.0, 0.0, fade) ** 2
        x[: int(0.002 * SR)] *= np.linspace(0.0, 1.0, int(0.002 * SR))  # de-click
    peak = np.abs(x).max()
    if peak > 0:
        x *= 10 ** (spec.get("peak_db", -3) / 20) / peak
    return x.astype(np.float32)


def output_name(spec):
    # Loops are PCM WAV: Vorbis encodes here sometimes lose the last 128 samples, which
    # makes the loop point click. One-shots are Ogg Vorbis.
    return spec["name"] + (".wav" if spec.get("loop") else ".ogg")


def encode(x, out):
    if out.endswith(".wav"):
        codec = ["-c:a", "pcm_s16le"]
    else:
        codec = ["-c:a", "libvorbis", "-q:a", "4"]
    cmd = ["ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ar", str(SR), "-ac", "1", "-i", "-"] + codec + [
        "-map_metadata", "-1", "-fflags", "+bitexact", "-flags:a", "+bitexact", out]
    subprocess.run(cmd, input=x.tobytes(), check=True)


def render_and_encode(spec, cache, packs, out):
    x = render(spec, cache, packs)
    encode(x, out)
    if spec.get("loop") and len(decode(out)) != len(x):
        raise RuntimeError("loop is not sample-exact: " + out)
    return x


def write_licenses(spec):
    packs = spec["packs"]
    lines = [BEGIN, "", "| Sound id | File | Source | Author | Licence | Processing |", "|---|---|---|---|---|---|"]
    for s in spec["sounds"]:
        p = packs[s["pack"]]
        src = p["title"] if s["pack"] == "synth" else "[%s](%s): `%s`" % (p["title"], p["page"], s["file"])
        proc = []
        if "start" in s or "length" in s:
            proc.append("cut %.2fs" % s.get("length", 0) if "length" in s else "cut")
        if s.get("loop"):
            proc.append("loop crossfade")
        if s.get("af"):
            proc.append(s["af"])
        proc.append("mono, normalised")
        lines.append("| %d | `sounds/%s` | %s | %s | %s | %s |" % (s["id"], output_name(s), src, p["author"], p["license"], ", ".join(proc)))
    lines += ["", END]
    text = open(LICENSES, encoding="utf-8").read()
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        text = head + "\n".join(lines) + rest.split(END, 1)[1]
    else:
        text = text.rstrip("\n") + "\n\n## Sound effects\n\n" + "\n".join(lines) + "\n"
    open(LICENSES, "w", encoding="utf-8").write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=os.path.join(HERE, ".cache"))
    args = ap.parse_args()
    spec = json.load(open(os.path.join(HERE, "sources.json"), encoding="utf-8"))
    os.makedirs(args.cache, exist_ok=True)
    os.makedirs(OUT_DIR, exist_ok=True)
    for f in os.listdir(OUT_DIR):  # outputs are fully regenerated
        os.remove(os.path.join(OUT_DIR, f))
    for s in spec["sounds"]:
        out = os.path.join(OUT_DIR, output_name(s))
        x = render_and_encode(s, args.cache, spec["packs"], out)
        print("%3d %-10s %.2fs %6.1f KB" % (s["id"], s["name"], len(x) / SR, os.path.getsize(out) / 1024))
    write_licenses(spec)
    return 0


if __name__ == "__main__":
    sys.exit(main())
